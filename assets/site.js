function dailySeed() {
  const d = new Date();
  return d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate();
}
function seededRandom(seed) {
  return function () {
    seed |= 0; seed = (seed + 0x6D2B79F5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function loadFlickr() {
  const status = document.getElementById('flickr-status');
  const grid   = document.getElementById('flickr-grid');
  const rand   = seededRandom(dailySeed());
  const order  = FLICKR_POOL.slice();
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  let next = 0;

  function addTile() {
    if (next >= order.length) return;
    const key = order[next++];
    const id  = key.split('/')[1].split('_')[0];
    const a = document.createElement('a');
    a.href = `https://www.flickr.com/photos/${FLICKR_USER_ID}/${id}/`;
    a.target = '_blank';
    a.rel = 'noopener';
    a.className = 'flickr-img-wrap';
    const img = document.createElement('img');
    img.src = `https://live.staticflickr.com/${key}.jpg`;
    img.alt = 'May 21 photo archive';
    img.loading = 'lazy';
    img.onerror = () => { a.remove(); addTile(); };
    a.appendChild(img);
    grid.appendChild(a);
  }

  if (status) status.style.display = 'none';
  grid.innerHTML = '';
  for (let i = 0; i < FLICKR_COUNT; i++) addTile();
  const more = document.getElementById('flickr-more');
  if (more) more.onclick = () => { for (let i = 0; i < FLICKR_COUNT; i++) addTile(); if (next >= order.length) more.hidden = true; };
}


