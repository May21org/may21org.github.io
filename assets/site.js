const LOCALES = { en: 'en-GB', kbd: 'ru-RU', ady: 'ru-RU', ru: 'ru-RU', tr: 'tr-TR', de: 'de-DE', ar: 'ar' };
function parseDay(s) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(s || ''));
  return m ? new Date(+m[1], +m[2] - 1, +m[3]) : null;
}
function fmtDay(d, lang, opts) {
  try { return new Intl.DateTimeFormat(LOCALES[lang] || 'en-GB', opts).format(d); }
  catch (e) { return d.toISOString().slice(0, 10); }
}
function fmtRange(ev, lang) {
  const a = parseDay(ev.date), b = parseDay(ev.end);
  if (!a) return escapeHtml(ev.date || '');
  const full = { day: 'numeric', month: 'short', year: 'numeric' };
  if (!b || b.getTime() === a.getTime()) return fmtDay(a, lang, full);
  if (a.getFullYear() === b.getFullYear() && a.getMonth() === b.getMonth())
    return a.getDate() + '–' + fmtDay(b, lang, full);
  if (a.getFullYear() === b.getFullYear())
    return fmtDay(a, lang, { day: 'numeric', month: 'short' }) + ' – ' + fmtDay(b, lang, full);
  return fmtDay(a, lang, full) + ' – ' + fmtDay(b, lang, full);
}
function eventStatus(ev) {
  const today = new Date(); today.setHours(0, 0, 0, 0);
  const a = parseDay(ev.date), b = parseDay(ev.end) || a;
  if (!a) return 'past';
  if (a > today) return 'upcoming';
  if (b >= today) return 'now';
  return 'past';
}
function renderEvent(entry, lang) {
  const ev = localized(entry, lang);
  const st = eventStatus(ev);
  const badgeKey = st === 'now' ? 'ev_now' : st === 'upcoming' ? 'ev_upcoming' : '';
  const badge = badgeKey ? `<span class="ev-status ${st}" data-i18n="${badgeKey}">${tr(lang, badgeKey)}</span>` : '';
  const meta = [ev.type ? `<span class="ev-type">${escapeHtml(ev.type)}</span>` : '', escapeHtml(ev.place || ''), escapeHtml(ev.lang || '')].filter(Boolean).join(' · ');
  const inner = `<div><div class="ev-when">${fmtRange(ev, lang)}</div>${badge}</div>
      <div>${meta ? `<p class="ev-meta">${meta}</p>` : ''}<div class="ev-title">${escapeHtml(ev.title)}</div>${ev.description ? `<p class="ev-desc">${escapeHtml(ev.description)}</p>` : ''}</div>
      ${ev.url ? `<span class="ev-open" data-i18n="ev_more">${tr(lang, 'ev_more')}</span>` : '<span></span>'}`;
  const body = ev.url
    ? `<a class="ev-link" href="${escapeHtml(ev.url)}" target="_blank" rel="noopener">${inner}</a>`
    : `<div class="ev-link">${inner}</div>`;
  return `<li class="ev-item ${st}">${body}</li>`;
}
