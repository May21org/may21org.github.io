const langLabels = { en: 'EN', kbd: 'КАБ', ady: 'АДЫ', ru: 'РУС', tr: 'TR', de: 'DE', ar: 'عر' };

// look up a key in the given language, falling back to English
function tr(lang, key) {
  const t = i18n[lang] || i18n.en;
  return t[key] !== undefined ? t[key] : i18n.en[key];
}

function setLang(lang, remember = true) {
  const t = i18n[lang];
  if (!t) return;

  // set document direction and lang
  document.body.setAttribute('lang', lang);
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', t.dir);

  // update all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = tr(lang, el.getAttribute('data-i18n'));
    if (v !== undefined) el.innerHTML = v;
  });

  // update placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const v = tr(lang, el.getAttribute('data-i18n-placeholder'));
    if (v !== undefined) el.setAttribute('placeholder', v);
  });

  // update ticker
  const tickerEl = document.getElementById('ticker');
  if (tickerEl && t.ticker) {
    const items = [...t.ticker, ...t.ticker]; // duplicate for seamless loop
    tickerEl.innerHTML = items.map(s => `<span>${s} &nbsp;·&nbsp;</span>`).join('');
  }

  // update lang button label
  document.getElementById('currentLangLabel').textContent = langLabels[lang] || lang.toUpperCase();

  // mark active option
  document.querySelectorAll('.lang-option').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('onclick') === `setLang('${lang}')`);
  });

  // re-render the library so per-language editions switch too
  if (typeof renderLibrary === 'function') renderLibrary();
  if (typeof renderRecognition === 'function') renderRecognition();
  if (typeof renderEvents === 'function') renderEvents();
  if (typeof renderHome === 'function') renderHome();

  // close dropdown
  document.getElementById('langSwitcher').classList.remove('open');

  // store preference
  if (remember) { try { localStorage.setItem('may21_lang', lang); } catch (e) {} }
}

function toggleLangMenu() {
  document.getElementById('langSwitcher').classList.toggle('open');
}

// close dropdown when clicking outside
document.addEventListener('click', e => {
  if (!document.getElementById('langSwitcher').contains(e.target)) {
    document.getElementById('langSwitcher').classList.remove('open');
  }
});

// on load: use the visitor's own choice if they made one,
// otherwise match their browser language (falls back to English)
function detectLang() {
  const prefs = navigator.languages && navigator.languages.length
    ? navigator.languages : [navigator.language || 'en'];
  for (const pref of prefs) {
    const code = String(pref).toLowerCase().split('-')[0];
    if (i18n[code]) return code;
  }
  return 'en';
}
